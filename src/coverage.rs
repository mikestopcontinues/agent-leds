//! What each harness can tell the daemon, crossed with the session table.
//!
//! Each harness declares the signals it produces, the channel each comes
//! through and how that is known. `render` turns the declarations into
//! `docs/coverage.md`: the moves a harness can never make, the phases it never
//! enters and the ones it cannot leave by itself. That document is the
//! evaluation of what is missing.

use std::collections::BTreeSet;

use serde::{Deserialize, Serialize};

use crate::fsm::{self, Channel, Phase, Signal, TABLE, To};
use crate::harness::Harness;

/// How a declaration is known.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Evidence {
    /// Seen in a real session of the harness.
    Observed,
    /// Read from the harness's code, its docs or someone else's captures.
    Inferred,
}

/// One signal a harness produces, on one channel, and what it is read from.
pub struct Declared {
    pub signal: Signal,
    pub channel: Channel,
    pub evidence: Evidence,
    /// What is read, such as "event_msg task_complete with error".
    pub record: &'static str,
    /// The probe run that shows it, such as "probe-codex runC".
    pub cite: &'static str,
}

impl Declared {
    pub const fn new(
        signal: Signal,
        channel: Channel,
        evidence: Evidence,
        record: &'static str,
        cite: &'static str,
    ) -> Declared {
        Declared {
            signal,
            channel,
            evidence,
            record,
            cite,
        }
    }
}

/// The coverage document for the harnesses' declarations, in the order given.
pub fn render(harnesses: &[(Harness, &[Declared])]) -> String {
    let mut out = vec![
        "# Coverage".to_owned(),
        String::new(),
        "Generated by `coverage::render` from the table in `src/fsm.rs` and the signals each \
         harness declares; `UPDATE_COVERAGE=1 cargo test` rewrites it."
            .to_owned(),
    ];
    out.extend(table());
    out.extend(matrix(harnesses));
    out.extend(missing(harnesses));
    out.extend(never_entered(harnesses));
    out.extend(stuck(harnesses));
    out.push(String::new());
    out.join("\n")
}

/// Part 1: every phase against every signal.
fn table() -> Vec<String> {
    let mut out = vec![
        String::new(),
        "## The table".to_owned(),
        String::new(),
        "Each cell is the phase the signal moves to; `·` means no rule, so the signal changes \
         nothing, and `back` is back to the phase the session entered its row's phase from. A \
         cell that names its own row's phase holds the session there against the signals ranked \
         after it; alone it changes nothing, but a turn that ends again is announced again."
            .to_owned(),
        String::new(),
    ];
    let shorts: Vec<&str> = Signal::ALL.into_iter().map(short).collect();
    out.push(format!("| from \\ on | {} |", shorts.join(" | ")));
    out.push(format!("|---|{}", "---|".repeat(Signal::ALL.len())));
    for from in Phase::ALL {
        let cells: Vec<String> = Signal::ALL
            .into_iter()
            .map(|on| match fsm::step(from, on) {
                None => "·".to_owned(),
                Some(To::Go(to)) => format!("{to:?}"),
                Some(To::Back) => "back".to_owned(),
            })
            .collect();
        out.push(format!("| {from:?} | {} |", cells.join(" | ")));
    }
    out.push(String::new());
    let legend: Vec<String> = Signal::ALL
        .into_iter()
        .map(|on| format!("{} ({on:?})", short(on)))
        .collect();
    out.push(format!("Columns: {}.", legend.join(", ")));
    let order: Vec<String> = fsm::priority()
        .into_iter()
        .map(|on| format!("{on:?}"))
        .collect();
    out.extend([
        String::new(),
        format!(
            "One record can tell several signals, each a fact of its own. The first of them in \
             this order with a rule from the session's phase is the move: {}.",
            order.join(", ")
        ),
        String::new(),
        "Signals of one family are told together by sound sessions:".to_owned(),
        String::new(),
    ]);
    for family in fsm::FAMILIES {
        let names: Vec<String> = family.iter().map(|on| format!("{on:?}")).collect();
        out.push(format!("- {}", names.join(", ")));
    }
    out.extend([
        String::new(),
        "Any other signals told together overlap: the order above still decides, and the daemon \
         counts each set in `agent-leds status --json` and `agent-leds doctor`."
            .to_owned(),
    ]);
    out
}

/// Part 2: the channels each harness produces each signal on, with the
/// records they are read from.
fn matrix(harnesses: &[(Harness, &[Declared])]) -> Vec<String> {
    let mut out = vec![
        String::new(),
        "## Signals by harness".to_owned(),
        String::new(),
        "Each cell is the channel a harness produces the signal on: `file`, `hook`, both, or `—` \
         for neither. `*` marks a channel known only from code, docs or someone else's captures, \
         not from a real session."
            .to_owned(),
        String::new(),
    ];
    let titles: Vec<&str> = harnesses.iter().map(|(h, _)| h.title()).collect();
    out.push(format!("| Signal | {} |", titles.join(" | ")));
    out.push(format!("| --- |{}", " --- |".repeat(harnesses.len())));
    let told: Vec<Signal> = Signal::ALL.into_iter().filter(|s| !s.daemon()).collect();
    for &signal in &told {
        let cells: Vec<String> = harnesses
            .iter()
            .map(|(_, declared)| cell(declared, signal))
            .collect();
        let declared = harnesses
            .iter()
            .any(|(_, declared)| declared.iter().any(|d| d.signal == signal));
        let name = if declared {
            format!("[{signal:?}](#{})", format!("{signal:?}").to_lowercase())
        } else {
            format!("{signal:?}")
        };
        out.push(format!("| {name} | {} |", cells.join(" | ")));
    }
    for signal in told {
        let records: Vec<String> = harnesses
            .iter()
            .flat_map(|(harness, declared)| {
                declared
                    .iter()
                    .filter(move |d| d.signal == signal)
                    .map(move |d| {
                        format!(
                            "- {}, {}, {}: {} ({})",
                            harness.title(),
                            channel(d.channel),
                            evidence(d.evidence),
                            d.record,
                            d.cite
                        )
                    })
            })
            .collect();
        if !records.is_empty() {
            out.extend([String::new(), format!("### {signal:?}"), String::new()]);
            out.extend(records);
        }
    }
    out
}

/// Part 3: the moves of the table a harness never makes, because it does not
/// produce their signal, from the phases it does reach.
fn missing(harnesses: &[(Harness, &[Declared])]) -> Vec<String> {
    let mut out = vec![
        String::new(),
        "## Moves each harness cannot make".to_owned(),
    ];
    let mut any = false;
    for signal in Signal::ALL.into_iter().filter(|s| !s.daemon()) {
        let mut lines = Vec::new();
        for (harness, declared) in harnesses {
            if declared.iter().any(|d| d.signal == signal) {
                continue;
            }
            let reached = reached(declared);
            for rule in TABLE.iter().filter(|rule| rule.on == signal) {
                // A row that holds a phase moves nothing.
                let from: Vec<String> = rule
                    .from
                    .iter()
                    .filter(|&&phase| reached.contains(&phase))
                    .filter(|&&phase| match rule.to {
                        To::Go(to) => phase != to || fsm::announces(phase, rule.on, to),
                        To::Back => true,
                    })
                    .map(|phase| format!("{phase:?}"))
                    .collect();
                let to = match rule.to {
                    To::Go(to) => format!("{to:?}"),
                    To::Back => "back to where it was found".to_owned(),
                };
                if !from.is_empty() {
                    lines.push(format!("- {}: {} → {to}", harness.title(), from.join(", ")));
                }
            }
        }
        if !lines.is_empty() {
            any = true;
            out.extend([
                String::new(),
                format!("**{signal:?}**: {}.", signal.when_missing()),
                String::new(),
            ]);
            out.extend(lines);
        }
    }
    if !any {
        out.extend([String::new(), "Every harness makes every move.".to_owned()]);
    }
    out
}

/// Part 4: the phases a harness never enters.
fn never_entered(harnesses: &[(Harness, &[Declared])]) -> Vec<String> {
    let mut out = vec![
        String::new(),
        "## Phases never entered".to_owned(),
        String::new(),
        "Searched from `Gone` over the signals a harness declares and the daemon's own.".to_owned(),
        String::new(),
    ];
    let mut lines = Vec::new();
    for (harness, declared) in harnesses {
        let reached = reached(declared);
        let never: Vec<String> = Phase::ALL
            .into_iter()
            .filter(|phase| !reached.contains(phase))
            .map(|phase| format!("{phase:?}"))
            .collect();
        if !never.is_empty() {
            lines.push(format!("- {}: {}", harness.title(), never.join(", ")));
        }
    }
    if lines.is_empty() {
        lines.push("Every harness enters every phase.".to_owned());
    }
    out.extend(lines);
    out
}

/// Part 5: the phases with a light that a harness reaches but leaves only
/// when its process ends or through the daemon's own signals.
fn stuck(harnesses: &[(Harness, &[Declared])]) -> Vec<String> {
    let mut out = vec![
        String::new(),
        "## Stuck phases".to_owned(),
        String::new(),
        "Phases with a light that a harness reaches but leaves only when its process ends or \
         through the daemon's own signals. Each is a place where an experiment or a deliberate \
         guess is worth considering."
            .to_owned(),
        String::new(),
    ];
    let mut lines = Vec::new();
    for (harness, declared) in harnesses {
        let signals = signals(declared);
        for phase in reached(declared) {
            if phase.state().is_none() {
                continue;
            }
            let leaves: Vec<Signal> = signals
                .iter()
                .copied()
                .filter(|&on| fsm::step(phase, on).is_some_and(|to| to != To::Go(phase)))
                .collect();
            if leaves.iter().all(|&on| on == Signal::Ended || on.daemon()) {
                let by: Vec<String> = leaves.iter().map(|on| format!("{on:?}")).collect();
                lines.push(format!(
                    "- {}, {phase:?}: left only by {}",
                    harness.title(),
                    by.join(", ")
                ));
            }
        }
    }
    if lines.is_empty() {
        lines.push("No harness has a stuck phase.".to_owned());
    }
    out.extend(lines);
    out
}

/// The signals a harness declares, with the daemon's own.
fn signals(declared: &[Declared]) -> BTreeSet<Signal> {
    Signal::ALL
        .into_iter()
        .filter(|&s| s.daemon() || declared.iter().any(|d| d.signal == s))
        .collect()
}

/// The phases a harness's sessions can enter.
fn reached(declared: &[Declared]) -> BTreeSet<Phase> {
    let signals: Vec<Signal> = signals(declared).into_iter().collect();
    fsm::reachable(Phase::Gone, &signals)
}

/// A matrix cell: each channel the signal is declared on, marked when every
/// declaration on it is inferred.
fn cell(declared: &[Declared], signal: Signal) -> String {
    let channels: BTreeSet<Channel> = declared
        .iter()
        .filter(|d| d.signal == signal)
        .map(|d| d.channel)
        .collect();
    if channels.is_empty() {
        return "—".to_owned();
    }
    let names: Vec<String> = channels
        .into_iter()
        .map(|c| {
            let inferred = declared
                .iter()
                .filter(|d| d.signal == signal && d.channel == c)
                .all(|d| d.evidence == Evidence::Inferred);
            format!("{}{}", channel(c), if inferred { "*" } else { "" })
        })
        .collect();
    names.join("+")
}

fn channel(channel: Channel) -> &'static str {
    match channel {
        Channel::File => "file",
        Channel::Hook => "hook",
        Channel::Daemon => "daemon",
    }
}

fn evidence(evidence: Evidence) -> &'static str {
    match evidence {
        Evidence::Observed => "observed",
        Evidence::Inferred => "inferred",
    }
}

/// A signal's column heading in the table.
fn short(signal: Signal) -> &'static str {
    match signal {
        Signal::Started => "Start",
        Signal::Prompted => "Prompt",
        Signal::PermissionAsked => "Perm",
        Signal::QuestionAsked => "Quest",
        Signal::Answered => "Answ",
        Signal::Released => "Rel",
        Signal::TurnEnded => "End",
        Signal::TurnEndedAsking => "End?",
        Signal::TurnFailed => "Fail",
        Signal::Interrupted => "Intr",
        Signal::Backgrounded => "Bg",
        Signal::BackgroundDone => "BgDone",
        Signal::Ended => "Ended",
        Signal::Looked => "Look",
        Signal::ReadExpired => "RdExp",
        Signal::Abandoned => "Aband",
        Signal::Dismissed => "Dism",
    }
}

